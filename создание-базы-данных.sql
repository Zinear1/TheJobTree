-- База данных веб-платформы TheJobTree (PostgreSQL)
-- Тема: Разработка БД и веб-приложения для объявлений о подработке и откликов

-- Очистка объектов при повторном запуске скрипта
DROP VIEW IF EXISTS user_ratings CASCADE;
DROP FUNCTION IF EXISTS accept_response(INT) CASCADE;
DROP FUNCTION IF EXISTS create_chat_on_response() CASCADE;

DROP TABLE IF EXISTS reviews CASCADE;
DROP TABLE IF EXISTS messages CASCADE;
DROP TABLE IF EXISTS chats CASCADE;
DROP TABLE IF EXISTS responses CASCADE;
DROP TABLE IF EXISTS user_skills CASCADE;
DROP TABLE IF EXISTS ad_skills CASCADE;
DROP TABLE IF EXISTS ads CASCADE;
DROP TABLE IF EXISTS skills CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- 1. Пользователи (единый профиль: работодатель и соискатель в одном аккаунте)
CREATE TABLE users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    phone         VARCHAR(20)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    city          VARCHAR(60)  NOT NULL,
    avatar_url    VARCHAR(255) DEFAULT '/static/uploads/default_avatar.png',
    bio           TEXT         DEFAULT '',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Категории объявлений (с поддержкой вложенных подкатегорий)
CREATE TABLE categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    parent_id   INT          REFERENCES categories(category_id) ON DELETE SET NULL
);

-- 3. Справочник навыков и софт-скиллов (для фильтров и профилей)
CREATE TABLE skills (
    skill_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    skill_type  VARCHAR(10)  NOT NULL CHECK (skill_type IN ('soft', 'hard')),
    category_id INT          REFERENCES categories(category_id) ON DELETE SET NULL
);

-- 4. Объявления о работе и подработке
CREATE TABLE ads (
    ad_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id   INT            NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    worker_id     INT            REFERENCES users(user_id) ON DELETE SET NULL,
    category_id   INT            NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    title         VARCHAR(150)   NOT NULL,
    description   TEXT           NOT NULL,
    budget        NUMERIC(10, 2) NOT NULL CHECK (budget > 0),
    city          VARCHAR(60)    NOT NULL,
    is_remote     BOOLEAN        NOT NULL DEFAULT FALSE,
    deadline_date DATE,
    status        VARCHAR(20)    NOT NULL DEFAULT 'активно'
                  CHECK (status IN ('активно', 'в работе', 'выполнено', 'отменено')),
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_ads_employer_not_worker CHECK (worker_id IS NULL OR employer_id <> worker_id)
);

-- 5. Связь M:N: требуемые софт-скиллы и навыки для объявления
CREATE TABLE ad_skills (
    ad_id    INT NOT NULL REFERENCES ads(ad_id) ON DELETE CASCADE,
    skill_id INT NOT NULL REFERENCES skills(skill_id) ON DELETE CASCADE,
    PRIMARY KEY (ad_id, skill_id)
);

-- 6. Связь M:N: навыки и софт-скиллы пользователя
CREATE TABLE user_skills (
    user_id  INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    skill_id INT NOT NULL REFERENCES skills(skill_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, skill_id)
);

-- 7. Отклики соискателей на объявления
CREATE TABLE responses (
    response_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id           INT            NOT NULL REFERENCES ads(ad_id) ON DELETE CASCADE,
    applicant_id    INT            NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    proposed_budget NUMERIC(10, 2) CHECK (proposed_budget IS NULL OR proposed_budget > 0),
    cover_letter    TEXT           NOT NULL,
    status          VARCHAR(20)    NOT NULL DEFAULT 'ожидает'
                    CHECK (status IN ('ожидает', 'принят', 'отклонен')),
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_response_ad_applicant UNIQUE (ad_id, applicant_id)
);

-- 8. Чаты (создаются автоматически 1:1 при отклике на объявление)
CREATE TABLE chats (
    chat_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id INT       NOT NULL UNIQUE REFERENCES responses(response_id) ON DELETE CASCADE,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. Сообщения внутри чата
CREATE TABLE messages (
    message_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id    INT       NOT NULL REFERENCES chats(chat_id) ON DELETE CASCADE,
    sender_id  INT       NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    body       TEXT      NOT NULL CHECK (LENGTH(TRIM(body)) > 0),
    sent_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read    BOOLEAN   NOT NULL DEFAULT FALSE
);

-- 10. Взаимные отзывы
CREATE TABLE reviews (
    review_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_id      INT       NOT NULL REFERENCES ads(ad_id) ON DELETE CASCADE,
    author_id  INT       NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    target_id  INT       NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    rating     SMALLINT  NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    TEXT      NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reviews_not_self CHECK (author_id <> target_id),
    CONSTRAINT uq_reviews_ad_author_target UNIQUE (ad_id, author_id, target_id)
);

-- Индексы для ускорения фильтрации, поиска и соединений

CREATE INDEX idx_ads_status_city    ON ads (status, city);
CREATE INDEX idx_ads_category       ON ads (category_id);
CREATE INDEX idx_ads_employer       ON ads (employer_id);
CREATE INDEX idx_ads_worker         ON ads (worker_id);
CREATE INDEX idx_ads_budget         ON ads (budget);
CREATE INDEX idx_ad_skills_skill    ON ad_skills (skill_id);
CREATE INDEX idx_responses_ad       ON responses (ad_id);
CREATE INDEX idx_responses_user     ON responses (applicant_id);
CREATE INDEX idx_messages_chat_time ON messages (chat_id, sent_at);
CREATE INDEX idx_reviews_target     ON reviews (target_id);

-- Триггер: проверка отклика и автоматическое создание чата

CREATE OR REPLACE FUNCTION create_chat_on_response()
RETURNS TRIGGER AS $$
DECLARE
    v_employer_id INT;
BEGIN
    SELECT employer_id INTO v_employer_id
    FROM ads
    WHERE ad_id = NEW.ad_id;

    IF v_employer_id = NEW.applicant_id THEN
        RAISE EXCEPTION 'Пользователь не может откликнуться на собственное объявление';
    END IF;

    INSERT INTO chats (response_id)
    VALUES (NEW.response_id);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_create_chat_on_response
AFTER INSERT ON responses
FOR EACH ROW
EXECUTE FUNCTION create_chat_on_response();

-- Функция: утверждение исполнителя по отклику

CREATE OR REPLACE FUNCTION accept_response(p_response_id INT)
RETURNS VOID AS $$
DECLARE
    v_ad_id        INT;
    v_applicant_id INT;
BEGIN
    SELECT ad_id, applicant_id
    INTO v_ad_id, v_applicant_id
    FROM responses
    WHERE response_id = p_response_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Отклик с ID % не найден', p_response_id;
    END IF;

    UPDATE responses
    SET status = 'принят'
    WHERE response_id = p_response_id;

    UPDATE responses
    SET status = 'отклонен'
    WHERE ad_id = v_ad_id
      AND response_id <> p_response_id
      AND status = 'ожидает';

    UPDATE ads
    SET worker_id = v_applicant_id,
        status    = 'в работе'
    WHERE ad_id = v_ad_id;
END;
$$ LANGUAGE plpgsql;

-- Представление (VIEW): динамический расчёт среднего рейтинга

CREATE OR REPLACE VIEW user_ratings AS
SELECT
    u.user_id,
    u.first_name,
    u.last_name,
    u.city,
    COUNT(r.review_id) AS reviews_count,
    COALESCE(ROUND(AVG(r.rating), 2), 0.00) AS avg_rating
FROM users u
LEFT JOIN reviews r ON u.user_id = r.target_id
GROUP BY u.user_id, u.first_name, u.last_name, u.city;